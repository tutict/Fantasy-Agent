"""Headless Godot playtest: run a generated prototype and measure it.

This is the missing half of the pipeline. Everything before this point proves
the prototype *compiles*; this proves the loop is *reachable*: a scripted bot
loads the real main scene, drives the real input actions, and reports what the
generated ``game_manager`` actually decided.

Two rules shape this module, both learned by running the engine:

1. **The probe runs outside the project.** Godot takes ``--script <absolute
   path>`` with ``--path <project>``, so nothing has to be written into the
   generated project and the playtest leaves the artefact untouched.

2. **Duration comes from the engine, never from frames.** A headless run
   advances ``_process`` far faster than real time (measured: 439 frames for
   3.0 seconds of game time), so a frame count is not a duration and a frame
   time is not a performance number. ``session_seconds`` is read back from
   ``game_manager._elapsed``.

What this can and cannot say: it is a **lower bound on playability**. A bot
can prove the objective is reachable, that failure fires, and that the run
restarts. It cannot say the slice is fun, and the report says so out loud.
"""

